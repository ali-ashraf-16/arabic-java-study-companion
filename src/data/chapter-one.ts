export const pricingScenario = {
  unitPrice: 100,
  quantity: 2,
  discountPercentage: 10,
  vatPercentage: 14,
};

export function getPricingWalkthrough() {
  const subtotal = Number((pricingScenario.unitPrice * pricingScenario.quantity).toFixed(2));
  const discountAmount = Number((subtotal * pricingScenario.discountPercentage / 100).toFixed(2));
  const taxableAmount = Number((subtotal - discountAmount).toFixed(2));
  const vatAmount = Number((taxableAmount * pricingScenario.vatPercentage / 100).toFixed(2));
  const incorrectVat = Number((subtotal * pricingScenario.vatPercentage / 100).toFixed(2));

  return {
    subtotal,
    discountAmount,
    taxableAmount,
    vatAmount,
    correctTotal: Number((taxableAmount + vatAmount).toFixed(2)),
    incorrectVat,
    incorrectTotal: Number((subtotal - discountAmount + incorrectVat).toFixed(2)),
  };
}

